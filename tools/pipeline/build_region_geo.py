#!/usr/bin/env python3
"""Per-region physical geography for the disaster model (docs/07-map-and-filters.md#regional-geography).

Zonal statistics of the map's region-ID raster (assets/map/world.gsmap, build_map.py) on a
5 arc-minute grid (4320 x 2160, cell areas weighted by cos(latitude)), written to
  assets/scenario/world2020/regions_geo.csv     one row per regions.csv region
  assets/scenario/2020/regions_geo.csv          one row per slice nation (iso3), area-weighted over
  assets/scenario/2008/regions_geo.csv          its map regions; ROW = every nation not in the slice

Columns:
  area_km2           land area of the region's cells (5' cells: 85.86 km2 x cos(latitude))
  lat, lon           area-weighted land centroid (spherical mean), degrees; slices: of the nation's
                     regions; empty for ROW (and area_km2 too)
  elevation_m        mean land elevation (ETOPO1 ice surface, negative values as 0)
  lecz_share         share of land in the low-elevation coastal zone: elevation < 10 m and within
                     2 cells (~18 km) of the ocean (McGranahan, Balk & Anderson 2007). "Ocean" is the
                     water connected to the open sea, so the Caspian and other lakes do not count.
  coastal            1 if a region cell is next to the ocean (nations: share of their regions)
  floodplain_share   pragmatic floodplain proxy: land below 100 m whose local relief (max - min
                     elevation in the 5 x 5 cell window, ~45 km) is under 50 m, i.e. low, flat
                     lowlands (deltas, coastal and river plains); LECZ cells are included
  precip_mm          mean annual precipitation (WorldClim 2.1 1970-2000, 10'), sum of monthly means
  precip_peak_month  wettest month 1..12
  precip_seasonality coefficient of variation of the 12 monthly means
  koppen             dominant Koppen-Geiger main class (A/B/C/D/E; Beck et al. 2023 via the map asset)

Regions with no cell on the 5' grid (tiny islands, enclaves) take the cell at their centroid,
then their nation's mean. Inputs: python3 tools/pipeline/fetch.py --map-only.
Usage: python3 tools/pipeline/build_region_geo.py [--raw data/raw] [--assets assets]
"""

import argparse
import array
import csv
import io
import math
import pathlib
import struct
import sys
import zipfile
import zlib
from collections import deque

from PIL import Image, ImageFilter

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_map as bm  # noqa: E402

Image.MAX_IMAGE_PIXELS = None
W, H = 4320, 2160
UNCLAIMED = 0xFFFF
CELL_KM2 = (2 * math.pi * 6371.0 / W) * (math.pi * 6371.0 / H)
GEN = "generated by tools/pipeline/build_region_geo.py - edit the pipeline"
COLUMNS = ["area_km2", "lat", "lon", "elevation_m", "lecz_share", "coastal", "floodplain_share", "precip_mm", "precip_peak_month",
           "precip_seasonality", "koppen"]
SOURCE_NOTE = ("Sources: geoBoundaries ADM1 raster (assets/map/world.gsmap), NOAA ETOPO1 (public domain), "
               "WorldClim 2.1 precipitation 1970-2000 (Fick & Hijmans 2017; only these aggregates are "
               "redistributed), Koppen-Geiger 1991-2020 (Beck et al. 2023, CC BY 4.0). LECZ after "
               "McGranahan et al. 2007; floodplain = land < 100 m with < 50 m relief in ~45 km.")


def read_asset(path):
    f = path.read_bytes()
    w, h, tw, th, nn, nr, ns = struct.unpack_from("<7I", f, 8)
    at = 8 + 28 + nn * 16 + nr * 24
    sections = {}
    for _ in range(ns):
        tag, raw, packed = struct.unpack_from("<4sII", f, at)
        at += 12
        sections[tag] = zlib.decompress(f[at:at + packed])
        at += packed
    return w, h, tw, th, sections


def koppen_letter(k):
    if 1 <= k <= 3:
        return "A"
    if 4 <= k <= 7:
        return "B"
    if 8 <= k <= 16:
        return "C"
    if 17 <= k <= 28:
        return "D"
    if k >= 29:
        return "E"
    return ""


def ocean_mask(ids):
    """Water cells (id 0) connected to the open ocean (flood fill from the southern ocean, x wraps)."""
    ocean = bytearray(W * H)
    seeds = [y * W + x for y in (int(H * 0.68),) for x in range(0, W, 7) if ids[y * W + x] == 0]
    q = deque(seeds)
    for s in seeds:
        ocean[s] = 1
    while q:
        i = q.popleft()
        y, x = divmod(i, W)
        for j in (y * W + (x + 1) % W, y * W + (x - 1) % W, i - W if y > 0 else -1, i + W if y + 1 < H else -1):
            if j >= 0 and not ocean[j] and ids[j] == 0:
                ocean[j] = 1
                q.append(j)
    return ocean


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw")
    ap.add_argument("--assets", default="assets")
    args = ap.parse_args()
    raw, assets = pathlib.Path(args.raw), pathlib.Path(args.assets)
    regions = bm.read_csv(assets / "scenario" / "world2020" / "regions.csv")
    nr = len(regions)

    id_w, id_h, tw, th, sec = read_asset(assets / "map" / "world.gsmap")
    if (tw, th) != (W, H):
        sys.exit(f"terrain grid {tw}x{th}, expected {W}x{H}")
    ids_img = Image.frombytes("I;16", (id_w, id_h), sec[b"IDS0"]).convert("I").resize((W, H), Image.NEAREST)
    ids = array.array("i", ids_img.tobytes())
    clim = sec[b"CLIM"]

    etopo, ncols, nrows = bm.load_etopo(raw / "map" / "etopo1_5min.asc")
    elev_img = etopo.resize((W, H), Image.BILINEAR, box=(0.5, 0.5, ncols - 0.5, nrows - 0.5))
    elev = array.array("f", elev_img.tobytes())
    relief = array.array("f", elev_img.filter(ImageFilter.MaxFilter(5)).tobytes())
    low = array.array("f", elev_img.filter(ImageFilter.MinFilter(5)).tobytes())
    del etopo, elev_img

    # Precipitation: 12 monthly grids at 10' (2160 x 1080) -> every 5' cell takes its 10' parent.
    prec = []
    with zipfile.ZipFile(raw / "map" / "wc2.1_10m_prec.zip") as z:
        for m in range(1, 13):
            im = Image.open(io.BytesIO(z.read(f"wc2.1_10m_prec_{m:02d}.tif")))
            prec.append(array.array("i", im.convert("I").tobytes()))
    pw = 2160

    print("ocean flood fill")
    ocean = ocean_mask(ids)
    near = Image.frombytes("L", (W, H), bytes(255 if o else 0 for o in ocean))
    near2 = near.filter(ImageFilter.MaxFilter(5)).tobytes()  # within 2 cells of ocean
    near1 = near.filter(ImageFilter.MaxFilter(3)).tobytes()  # adjacent

    print("zonal statistics")
    area = [0.0] * (nr + 1)
    s_elev = [0.0] * (nr + 1)
    s_lecz = [0.0] * (nr + 1)
    s_flood = [0.0] * (nr + 1)
    coast = [0] * (nr + 1)
    cx = [0.0] * (nr + 1)
    cy = [0.0] * (nr + 1)
    cz = [0.0] * (nr + 1)
    p_area = [0.0] * (nr + 1)
    s_prec = [[0.0] * 12 for _ in range(nr + 1)]
    kcount = [dict() for _ in range(nr + 1)]
    for y in range(H):
        lat = 90.0 - (y + 0.5) * 180.0 / H
        a = math.cos(math.radians(lat))
        sin_lat = math.sin(math.radians(lat))
        row = y * W
        prow = (y // 2) * pw
        for x in range(W):
            i = row + x
            r = ids[i]
            if r <= 0 or r == UNCLAIMED or r > nr:
                continue
            e = elev[i]
            if e < 0.0:
                e = 0.0
            area[r] += a
            lon_r = math.radians(-180.0 + (x + 0.5) * 360.0 / W)
            cx[r] += a * a * math.cos(lon_r)
            cy[r] += a * a * math.sin(lon_r)
            cz[r] += a * sin_lat
            s_elev[r] += a * e
            if e < 10.0 and near2[i]:
                s_lecz[r] += a
            if e < 100.0 and relief[i] - low[i] < 50.0:
                s_flood[r] += a
            if near1[i]:
                coast[r] = 1
            k = koppen_letter(clim[i])
            if k:
                kcount[r][k] = kcount[r].get(k, 0.0) + a
            pi = prow + x // 2
            v0 = prec[0][pi]
            if v0 > -1000:
                p_area[r] += a
                sp = s_prec[r]
                for m in range(12):
                    sp[m] += a * prec[m][pi]

    def stats(r):
        if area[r] <= 0.0:
            return None
        monthly = [s / p_area[r] for s in s_prec[r]] if p_area[r] > 0 else None
        out = {"area_km2": area[r] * CELL_KM2, "lat": math.degrees(math.atan2(cz[r], math.hypot(cx[r], cy[r]))),
               "lon": math.degrees(math.atan2(cy[r], cx[r])), "elevation_m": s_elev[r] / area[r], "lecz_share": s_lecz[r] / area[r], "coastal": coast[r],
               "floodplain_share": s_flood[r] / area[r], "koppen": max(kcount[r], key=kcount[r].get) if kcount[r] else ""}
        if monthly:
            mean = sum(monthly) / 12.0
            sd = math.sqrt(sum((v - mean) ** 2 for v in monthly) / 12.0)
            out.update(precip_mm=sum(monthly), precip_peak_month=1 + monthly.index(max(monthly)),
                       precip_seasonality=sd / mean if mean > 0 else 0.0)
        return out, area[r]

    def cell_at(lon, lat):
        x = min(W - 1, int((lon + 180.0) / 360.0 * W))
        y = min(H - 1, int((90.0 - lat) / 180.0 * H))
        i = y * W + x
        e = max(0.0, elev[i])
        pi = (y // 2) * pw + x // 2
        monthly = [prec[m][pi] for m in range(12)]
        out = {"elevation_m": e, "lecz_share": 1.0 if e < 10.0 and near2[i] else 0.0, "coastal": 1 if near1[i] else 0,
               "floodplain_share": 1.0 if e < 100.0 and relief[i] - low[i] < 50.0 else 0.0,
               "koppen": koppen_letter(clim[i])}
        if monthly[0] > -1000:
            mean = sum(monthly) / 12.0
            sd = math.sqrt(sum((v - mean) ** 2 for v in monthly) / 12.0)
            out.update(precip_mm=float(sum(monthly)), precip_peak_month=1 + monthly.index(max(monthly)),
                       precip_seasonality=sd / mean if mean > 0 else 0.0)
        return out

    # Per region, then nation means for the gaps.
    per, weight = {}, {}
    for idx, reg in enumerate(regions):
        s = stats(idx + 1)
        if s:
            per[idx], weight[idx] = s[0], s[1]
    by_nation = {}
    for idx, reg in enumerate(regions):
        by_nation.setdefault(reg["iso3"], []).append(idx)

    def mean_of(idxs, wts):
        tot = sum(wts[i] for i in idxs)
        out = {}
        for c in COLUMNS:
            vals = [(per[i][c], wts[i]) for i in idxs if c in per[i] and per[i][c] != ""]
            if not vals:
                continue
            if c == "area_km2":
                out[c] = sum(v for v, _ in vals)
                continue
            if c in ("lat", "lon"):
                continue
            if c == "koppen":
                acc = {}
                for v, wt in vals:
                    acc[v] = acc.get(v, 0.0) + wt
                out[c] = max(acc, key=acc.get)
            elif c == "precip_peak_month":
                out[c] = max(vals, key=lambda t: t[1])[0]  # the largest region's
            else:
                sw = sum(wt for _, wt in vals)
                out[c] = sum(v * wt for v, wt in vals) / sw if sw > 0 else vals[0][0]
        pts = [(per[i]["lon"], per[i]["lat"], wts[i]) for i in idxs if "lat" in per[i]]
        if pts:
            out["lon"], out["lat"] = bm.circular_mean(pts)
        return out, tot

    nation_mean = {iso: mean_of([i for i in idxs if i in per], weight)[0] for iso, idxs in by_nation.items()}
    filled = 0
    for idx, reg in enumerate(regions):
        if idx in per and all(c in per[idx] and per[idx][c] != "" for c in COLUMNS):
            continue
        base = cell_at(float(reg["lon"]), float(reg["lat"]))
        base.update(area_km2=float(reg["area_km2"] or 0.0), lat=float(reg["lat"]), lon=float(reg["lon"]))
        for c, v in nation_mean.get(reg["iso3"], {}).items():
            if c not in base or base[c] == "":
                base[c] = v
        merged = dict(base)
        merged.update({c: v for c, v in per.get(idx, {}).items() if v != ""})
        per[idx] = merged
        weight.setdefault(idx, max(1e-3, float(reg["area_km2"] or 1.0) / 1e5))
        filled += 1
    print(f"{len(regions) - filled} regions from their cells, {filled} with centroid / nation fallbacks")

    def fmt(row):
        out = []
        for c in COLUMNS:
            v = row.get(c, "")
            if c in ("coastal", "precip_peak_month") and v != "":
                out.append(f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) and c == "coastal" else str(int(round(v))))
            elif isinstance(v, float):
                if c in ("lat", "lon"):
                    out.append(f"{v:.4f}")
                elif c in ("precip_mm", "elevation_m", "area_km2"):
                    out.append(f"{v:.1f}")
                else:
                    out.append(f"{v:.4g}")
            else:
                out.append(str(v))
        return out

    def write(path, header, rows, columns=None):
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", newline="", encoding="utf-8") as f:
            f.write(f"# {header}\n")
            w = csv.writer(f, lineterminator="\n")
            w.writerow(columns or ["region", "iso3"] + COLUMNS)
            for r in rows:
                w.writerow(r)
        print(f"wrote {path} ({len(rows)} rows)")

    # The world's regions carry their nation, area and centroid in regions.csv: only the
    # geography columns here (the slices, without a regions.csv, keep them all).
    geo_only = [c for c in COLUMNS if c not in ("area_km2", "lat", "lon")]
    keep = [COLUMNS.index(c) for c in geo_only]
    write(assets / "scenario" / "world2020" / "regions_geo.csv", f"{GEN}. {SOURCE_NOTE}",
          [[reg["region"]] + [fmt(per[idx])[k] for k in keep] for idx, reg in enumerate(regions)],
          ["region"] + geo_only)

    # Slices: one row per nation (iso3); ROW = all world2020 nations outside the slice.
    for slice_name in ("2020", "2008"):
        nations = [r["iso3"] for r in bm.read_csv(assets / "scenario" / slice_name / "nations.csv")]
        rows = []
        for iso in nations:
            if iso == "ROW":
                idxs = [i for i, reg in enumerate(regions) if reg["iso3"] not in nations]
            else:
                idxs = by_nation.get(iso, [])
            if not idxs:
                print(f"warning: {slice_name}: no regions for {iso}")
                continue
            m, _ = mean_of(idxs, weight)
            m["coastal"] = sum(per[i]["coastal"] for i in idxs) / len(idxs)  # share of coastal regions
            if iso == "ROW":
                for c in ("area_km2", "lat", "lon"):
                    m[c] = ""
            rows.append([iso, iso] + fmt(m))
        write(assets / "scenario" / slice_name / "regions_geo.csv",
              f"{GEN}. One row per nation (region = iso3), area-weighted over its world2020 map regions; "
              f"coastal = share of coastal regions; ROW = every nation outside the slice. {SOURCE_NOTE}", rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
