def policy_rate_events(raw, filename="bis_cbpol.csv", iso2=ISO2, euro=EURO_AREA, start="2020-01-01", end="2020-12-31"):
    series = defaultdict(list)
    with (raw / filename).open(newline="") as f:
        for r in csv.DictReader(f):
            v = num(r["OBS_VALUE"])
            if v is not None:
                series[r["REF_AREA"]].append((r["TIME_PERIOD"], v))
    iso_for_area = defaultdict(list)
    for iso, a in iso2.items():
        iso_for_area["XM" if iso in euro else a].append(iso)
    out = [f"# {GEN}", f"# Source: BIS WS_CBPOL daily policy rates. Initial {start} value plus each change to {end}.",
           "# Euro area (XM) rate applies to every euro member.", ""]
    n = 0
    seen = set()
    for area, obs in sorted(series.items()):
        obs = sorted(set(obs))
        last = None
        initial = [v for d, v in obs if d <= start]
        if initial:
            last = initial[-1]
            for iso in iso_for_area.get(area, []):
                out.append(f"policy_rate{{ date{{{start}}} nation{{{iso}}} rate_pct{{{fmt(last, 3)}}} }}")
                n += 1
        for d, v in obs:
            if d <= start or d > end or v == last:
                continue
            for iso in iso_for_area.get(area, []):
                line = f"policy_rate{{ date{{{d}}} nation{{{iso}}} rate_pct{{{fmt(v, 3)}}} }}"
                if line not in seen:
                    seen.add(line)
                    out.append(line)
                    n += 1
            last = v
    return "\n".join(out) + "\n", n


# ---------------------------------------------------------------- targets

def targets(wdi, ox, nations, isos=SLICE):
    rows = []
    for iso in isos:
        g = lambda f: wdi[f].get(iso, {}).get(2020)
        deaths = None
        for r in ox.get(iso, []):
            if r["Date"] == "20201231":
                deaths = num(r["ConfirmedDeaths"])
        dpm = deaths / nations[iso]["population"] * 1e6 if deaths is not None else None
        rows.append([iso, g("real_gdp_growth_pct"), g("unemployment_pct"), g("cpi_inflation_pct"),
                     g("gov_net_lending_pct"), dpm])
    return rows


def brent(raw, year=2020):
    rows = []
    with (raw / "brent.csv").open(newline="") as f:
        for r in csv.DictReader(f):
            if r["Date"].startswith(str(year)) and r["Price"]:
                rows.append([r["Date"], float(r["Price"])])
    return rows


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw")
    ap.add_argument("--assets", default="assets")
    args = ap.parse_args()
    raw, assets = pathlib.Path(args.raw), pathlib.Path(args.assets)
    scen = assets / "scenario" / "2020"
    events = assets / "events" / "2020"
    events.mkdir(parents=True, exist_ok=True)

    wdi = load_wdi(raw)
    curated = read_curated(scen / "nations_curated.csv")
    nations = build_nations(wdi, curated)
    wgi = load_wgi(raw)
    # Capital coordinates (World Bank country metadata) for distances; ROW at a world centroid.
    meta_path = raw / "wb_countries.json"
    coords = {}
    if meta_path.exists():
        for c in json.loads(meta_path.read_text())[1]:
            if c.get("latitude"):
                coords[c["id"]] = (float(c["latitude"]), float(c["longitude"]))
    for iso in nations:
        nations[iso]["capital_lat"], nations[iso]["capital_lon"] = coords.get(iso, (20.0, 20.0))
    pops = {i: nations[i]["population"] for i in nations if i != ROW}
    for field, col in (("voice", "voice_est"), ("effectiveness", "gov_effectiveness_est")):
        for iso in nations:
            nations[iso][col] = wgi[field].get(iso)
        # ROW: population-weighted mean of every non-slice WGI country.
        rest = [(v, 1.0) for k, v in wgi[field].items() if k not in pops]
        nations[ROW][col] = sum(v for v, _ in rest) / len(rest) if rest else 0.0

    cols = ["iso3", "name", "population", "pop_0_14_pct", "pop_65up_pct", "labor_force",
            "unemployment_pct", "lfp_rate_pct", "gdp_usd", "gdp_ppp", "trend_growth_pct",
            "inflation_trend_pct", "hh_cons_pct", "gov_cons_pct", "investment_pct", "exports_pct",
            "imports_pct", "gov_revenue_pct", "gov_net_lending_pct", "gov_debt_pct", "gini",
            "hospital_beds_per_1000", "tertiary_attainment_pct", "urban_pct", "vulnerable_emp_pct",
            "voice_est", "gov_effectiveness_est", "birth_rate_per_1000", "death_rate_per_1000",
            "capital_lat", "capital_lon", "remittances_in_pct", "remittances_out_usd"]
    order = SLICE + [ROW]
    write_csv(scen / "nations.csv", cols, [[nations[i].get(c) for c in cols] for i in order],
              f"{GEN}. Source: World Bank WDI, latest year <= 2019; WGI voice/effectiveness (ROW: unweighted mean of the rest). Empty = missing (loader uses defaults).")

    srows = []
    for iso in order:
        va, emp = sector_split(wdi, iso, nations[iso])
        for s in SECTORS:
            srows.append([iso, s, va[s], emp[s]])
    write_csv(scen / "sectors.csv", ["iso3", "sector", "va_share", "emp_share"], srows,
              f"{GEN}. Source: WDI 3-sector VA/employment + resource rents, split into 7 sectors (see pipeline constants).")

    ox = load_oxcgrt(raw)
    pop = {}
    for r in json.loads((raw / "wdi_population_all.json").read_text())[1] or []:
        if r["value"] is not None and r["countryiso3code"]:
            pop[r["countryiso3code"]] = float(r["value"])
    text, n_npi = npi_events(ox, pop)
    (events / "npi.txt").write_text(text)
    text, n_rates = policy_rate_events(raw)
    (events / "policy_rates.txt").write_text(text)
    text, n_fiscal = fiscal_events(ox, nations)
    (events / "fiscal.txt").write_text(text)
    (events / "epidemic_seeds.txt").write_text(epidemic_seeds(ox))

    write_csv(assets / "backtest" / "2020_targets.csv",
              ["iso3", "gdp_growth_pct", "unemployment_pct", "inflation_pct", "gov_net_lending_pct",
               "deaths_per_million"],
              targets(wdi, ox, nations),
              f"{GEN}. Real 2020 outcomes: WDI (growth, unemployment, CPI, net lending), OxCGRT (deaths to 2020-12-31).")
    write_csv(assets / "backtest" / "2020_brent.csv", ["date", "usd_per_barrel"], brent(raw),
              f"{GEN}. Brent daily spot, EIA RBRTE.")

    lines = [f"# {GEN}", "", "Generated data sources:"]
    for name, url, lic in SOURCES:
        lines.append(f"- {name}\n  {url}\n  Licence: {lic}")
    lines += ["", "Hand-written (curated) files list their own sources inline:",
              "- assets/scenario/2020/nations_curated.csv",
              "- assets/events/2020/curated.txt",
              "- assets/defs/*.txt"]
    (assets / "SOURCES.txt").write_text("\n".join(lines) + "\n")
    print(f"nations={len(order)} npi_events={n_npi} rate_events={n_rates} fiscal_events={n_fiscal}")
    return 0


