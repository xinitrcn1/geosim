#!/usr/bin/env python3
"""Turn raw downloads (data/raw/, see fetch.py) into moddable assets/.

Outputs (all generated files carry a "generated by" header line or column):
  assets/scenario/2020/nations.csv          macro state per nation (2019 data)
  assets/scenario/2020/sectors.csv          value-added and employment shares per nation x sector
  assets/events/2020/npi.txt                lockdown level changes (OxCGRT)
  assets/events/2020/policy_rates.txt       central bank rate changes (BIS)
  assets/events/2020/fiscal.txt             fiscal packages (OxCGRT E3, scaled)
  assets/events/2020/epidemic_seeds.txt     first-infection seeds (OxCGRT confirmed cases)
  assets/backtest/2020_targets.csv          real 2020 outcomes per nation (WDI, OxCGRT)
  assets/backtest/2020_brent.csv            daily Brent 2020 (EIA)
  assets/SOURCES.txt                        provenance and licences

Hand-written files (assets/defs/*, assets/scenario/2020/*_curated.csv,
assets/events/2020/curated.txt) are read but never overwritten.

Usage: python3 tools/pipeline/build_assets.py [--raw data/raw] [--assets assets]
"""

import argparse
import csv
import datetime as dt
import json
import pathlib
import sys
from collections import defaultdict

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from countries import SLICE, ROW, ISO2, EURO_AREA  # noqa: E402
from fetch import WDI_INDICATORS, SOURCES  # noqa: E402

GEN = "generated by tools/pipeline/build_assets.py - edit the pipeline or override in *_curated files"

SECTORS = ["agr", "ene", "man", "con", "csv", "osv", "gov"]

# Share of non-government services that are contact-intensive (retail, wholesale,
# transport, accommodation and food, arts/recreation). ~0.38 in OECD STAN
# value-added data for 2019; used where no sector detail is available.
CONTACT_SERVICES_SHARE = 0.38
# Public-sector value added as a share of government consumption (compensation of
# employees is ~55-65% of general government final consumption, OECD NA).
GOV_VA_PER_GOV_CONSUMPTION = 0.6
# Relative labour intensity used to split WDI's 3-sector employment shares into
# 7 sectors (employment share within group ~ VA share x intensity).
LABOR_INTENSITY = {"ene": 0.25, "man": 1.0, "con": 1.3, "csv": 1.4, "osv": 0.8, "gov": 1.0}

# OxCGRT indicators used as NPI levels. Order is the asset key, not an index.
NPI_COLUMNS = {
    "C1": "C1M_School closing",
    "C2": "C2M_Workplace closing",
    "C3": "C3M_Cancel public events",
    "C4": "C4M_Restrictions on gatherings",
    "C5": "C5M_Close public transport",
    "C6": "C6M_Stay at home requirements",
    "C7": "C7M_Restrictions on internal movement",
    "C8": "C8EV_International travel controls",
    "E1": "E1_Income support",
    "H2": "H2_Testing policy",
    "H3": "H3_Contact tracing",
    "H6": "H6M_Facial Coverings",
}

# Fiscal: OxCGRT E3 records announced measures in USD, including loans and
# guarantees. Only part is "above the line" spending; IMF Fiscal Monitor
# comparisons put that at roughly half for advanced economies. A per-nation cap
# stops outliers (e.g. CHN local-government bond programmes) from dominating.
FISCAL_ABOVE_LINE_FRACTION = 0.5
FISCAL_CAP_PCT_GDP = 8.0


# ---------------------------------------------------------------- helpers

def load_wdi(raw: pathlib.Path, sub: str = "wdi"):
    """-> {field: {iso3: {year: value}}}"""
    out = {}
    for code, field in WDI_INDICATORS.items():
        payload = json.loads((raw / sub / f"{code}.json").read_text())
        series = defaultdict(dict)
        names = {}
        for row in payload[1] or []:
            iso = row["countryiso3code"]
            names[iso] = row["country"]["value"]
            if row["value"] is not None:
                series[iso][int(row["date"])] = float(row["value"])
        out[field] = series
        out.setdefault("_names", {}).update(names)
    return out


def load_wgi(raw: pathlib.Path, sub: str = "wdi_all"):
    """-> {"voice": {iso: v}, "effectiveness": {iso: v}}: latest WGI estimates in the file."""
    out = {}
    for code, field in (("GOV_WGI_VA.EST", "voice"), ("GOV_WGI_GE.EST", "effectiveness")):
        path = raw / sub / f"WGI_{code}.json"
        vals = {}
        if path.exists():
            rows = json.loads(path.read_text())[1] or []
            for r in sorted(rows, key=lambda r: r["date"]):
                if r["value"] is not None:
                    vals[r["countryiso3code"]] = float(r["value"])
        out[field] = vals
    return out


def latest(wdi, field, iso, year=2019, back=9):
    s = wdi[field].get(iso, {})
    for y in range(year, year - back - 1, -1):
        if y in s:
            return s[y]
    return None


def mean_years(wdi, field, iso, years):
    vals = [wdi[field].get(iso, {}).get(y) for y in years]
    vals = [v for v in vals if v is not None]
    return sum(vals) / len(vals) if vals else None


def read_curated(path: pathlib.Path):
    if not path.exists():
        return {}
    with path.open() as f:
        rows = [r for r in csv.DictReader(line for line in f if not line.startswith("#"))]
    return {r["iso3"]: r for r in rows}


def fmt(x, nd=4):
    if x is None:
        return ""
    if isinstance(x, str):
        return x
    return f"{x:.{nd}f}".rstrip("0").rstrip(".") if abs(x) < 1e6 else f"{x:.0f}"


def write_csv(path: pathlib.Path, header, rows, comment):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        f.write(f"# {comment}\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([fmt(v) if not isinstance(v, str) else v for v in r])


def ymd(s: str) -> str:
    return f"{s[0:4]}-{s[4:6]}-{s[6:8]}"


# ---------------------------------------------------------------- nations

def build_nations(wdi, curated, year=2019):
    """Macro state for SLICE + ROW (ROW = WLD minus SLICE) at the end of `year`."""
    rows = {}
    names = wdi["_names"]
    trend_years, inflation_years = range(year - 4, year + 1), range(year - 2, year + 1)

    def nation_row(iso):
        g = lambda f, y=year: latest(wdi, f, iso, y)
        r = {
            "iso3": iso, "name": names.get(iso, iso),
            "population": g("population"), "pop_0_14_pct": g("pop_0_14_pct"),
            "pop_65up_pct": g("pop_65up_pct"), "labor_force": g("labor_force"),
            "unemployment_pct": g("unemployment_pct"), "lfp_rate_pct": g("lfp_rate_pct"),
            "gdp_usd": g("gdp_usd"), "gdp_ppp": g("gdp_ppp"),
            "trend_growth_pct": mean_years(wdi, "real_gdp_growth_pct", iso, trend_years),
            "inflation_trend_pct": mean_years(wdi, "cpi_inflation_pct", iso, inflation_years),
            "hh_cons_pct": g("hh_cons_pct"), "gov_cons_pct": g("gov_cons_pct"),
            "investment_pct": g("investment_pct"), "exports_pct": g("exports_pct"),
            "imports_pct": g("imports_pct"), "gov_revenue_pct": g("gov_revenue_pct"),
            "gov_net_lending_pct": g("gov_net_lending_pct"), "gov_debt_pct": g("gov_debt_pct"),
            "gini": g("gini"), "hospital_beds_per_1000": g("hospital_beds_per_1000"),
            "tertiary_attainment_pct": g("tertiary_attainment_pct"), "urban_pct": g("urban_pct"),
            "vulnerable_emp_pct": g("vulnerable_emp_pct"),
            "birth_rate_per_1000": g("birth_rate_per_1000"), "death_rate_per_1000": g("death_rate_per_1000"),
            "remittances_in_pct": g("remittances_in_pct"), "remittances_out_usd": g("remittances_out_usd"),
        }
        return r

    for iso in SLICE:
        rows[iso] = nation_row(iso)

    # ROW: additive quantities are residuals of WLD; ratios are weighted residuals.
    w = nation_row("WLD")
    row = {"iso3": ROW, "name": "Rest of world"}
    for f in ("population", "labor_force", "gdp_usd", "gdp_ppp"):
        row[f] = w[f] - sum(rows[i][f] for i in SLICE)
    row["remittances_out_usd"] = (w["remittances_out_usd"] or 0) - sum(rows[i]["remittances_out_usd"] or 0 for i in SLICE)

    def residual_ratio(field, weight):
        tot = w[field] * w[weight] if w[field] is not None else None
        if tot is None:
            return None
        part = sum((rows[i][field] or w[field]) * rows[i][weight] for i in SLICE)
        return (tot - part) / row[weight]

    for f in ("hh_cons_pct", "gov_cons_pct", "investment_pct", "exports_pct", "imports_pct",
              "gov_revenue_pct", "trend_growth_pct"):
        row[f] = residual_ratio(f, "gdp_usd") if f != "trend_growth_pct" else None
    for f in ("pop_0_14_pct", "pop_65up_pct", "urban_pct", "hospital_beds_per_1000",
              "birth_rate_per_1000", "death_rate_per_1000"):
        row[f] = residual_ratio(f, "population")
    row["remittances_in_pct"] = residual_ratio("remittances_in_pct", "gdp_usd")
    row["unemployment_pct"] = residual_ratio("unemployment_pct", "labor_force")
    row["vulnerable_emp_pct"] = residual_ratio("vulnerable_emp_pct", "labor_force")
    row["lfp_rate_pct"] = w["lfp_rate_pct"]
    row["trend_growth_pct"] = mean_years(wdi, "real_gdp_growth_pct", "WLD", trend_years)
    row["inflation_trend_pct"] = mean_years(wdi, "cpi_inflation_pct", "WLD", inflation_years)
    for f in ("gov_net_lending_pct", "gov_debt_pct", "gini", "tertiary_attainment_pct"):
        row[f] = None
    rows[ROW] = row

    # Curated per-nation values (hemisphere, oil, labour institutions, gaps).
    for iso, r in rows.items():
        c = curated.get(iso, {})
        for k, v in c.items():
            if k in ("iso3", "source", "note") or v == "":
                continue
            if k in r and r[k] is not None and not k.startswith("override_"):
                continue  # curated values only fill gaps unless prefixed override_
            r[k.removeprefix("override_")] = float(v) if v.replace(".", "", 1).replace("-", "", 1).isdigit() else v
    return rows


def sector_split(wdi, iso, nation, fallback=None, year=2019):
    """7-sector VA and employment shares from WDI's 3-sector data.
    `fallback(field)` supplies a value when the nation has none (e.g. a group median)."""
    src = "WLD" if iso == ROW else iso

    def g(f):
        v = latest(wdi, f, src, year)
        return fallback(f) if v is None and fallback else v
    agr, ind, srv = g("va_agr_pct") or 4.0, g("va_ind_pct") or 28.0, g("va_srv_pct") or 64.0
    man = g("va_man_pct") or ind * 0.55
    rents = sum(x or 0.0 for x in (g("oil_rents_pct"), g("gas_rents_pct"), g("coal_rents_pct")))
    tot = agr + ind + srv
    agr, ind, srv, man, rents = (x / tot for x in (agr, ind, srv, man, rents))
    ene = min(max(ind - man - 0.02, 0.01), 0.8 * rents + 0.025)
    con = max(ind - man - ene, 0.01)
    gov = min(GOV_VA_PER_GOV_CONSUMPTION * (nation["gov_cons_pct"] or 16.0) / 100.0, 0.45 * srv)
    csv_ = (srv - gov) * CONTACT_SERVICES_SHARE
    osv = srv - gov - csv_
    va = dict(agr=agr, ene=ene, man=man, con=con, csv=csv_, osv=osv, gov=gov)
    s = sum(va.values())
    va = {k: v / s for k, v in va.items()}

    e_agr = (g("emp_agr_pct") or 25.0) / 100
    e_ind = (g("emp_ind_pct") or 22.0) / 100
    e_srv = (g("emp_srv_pct") or 53.0) / 100
    te = e_agr + e_ind + e_srv
    e_agr, e_ind, e_srv = e_agr / te, e_ind / te, e_srv / te
    emp = {"agr": e_agr}
    for group, members, total in (("ind", ("ene", "man", "con"), e_ind), ("srv", ("csv", "osv", "gov"), e_srv)):
        weights = {m: va[m] * LABOR_INTENSITY[m] for m in members}
        ws = sum(weights.values())
        for m in members:
            emp[m] = total * weights[m] / ws
    return va, emp


# ---------------------------------------------------------------- OxCGRT

def load_oxcgrt(raw):
    by_country = defaultdict(list)
    with (raw / "oxcgrt_compact_national.csv").open(newline="") as f:
        for r in csv.DictReader(f):
            if r["Jurisdiction"] != "NAT_TOTAL" or not ("20200101" <= r["Date"] <= "20201231"):
                continue
            by_country[r["CountryCode"]].append(r)
    for rows in by_country.values():
        rows.sort(key=lambda r: r["Date"])
    return by_country


def num(s):
    """Float or None; NaN/inf (BIS uses "NaN" for missing days) count as missing."""
    try:
        v = float(s)
    except (TypeError, ValueError):
        return None
    return v if v == v and abs(v) != float("inf") else None


# OxCGRT C/H "M" columns hold the strictest level anywhere in the country; the
# matching _Flag column is 1 for a general (nationwide) measure and 0 for a
# targeted one. The level is kept as is; the event also carries the targeted
# share (0..1) and the simulation decides how targeting scales each effect.


def npi_level(r, col):
    """-> (level, targeted share) or (None, 0)."""
    v = num(r[col])
    if v is None:
        return None, 0.0
    flag_col = col.split("_")[0] + "_Flag"
    targeted = 0.0
    if flag_col in r and v > 0:
        f = num(r[flag_col])
        if f is not None and f == 0:
            targeted = 1.0
    return v, targeted


def npi_events(ox, pop_by_iso, isos=SLICE, with_row=True):
    """Emit an event whenever an NPI level changes. ROW = population-weighted
    weekly mean over every OxCGRT country outside `isos` (slice scenario only)."""
    lines = []
    for iso in isos:
        last = {}
        for r in ox.get(iso, []):
            for key, col in NPI_COLUMNS.items():
                v, t = npi_level(r, col)
                if v is None:
                    v, t = last.get(key, (0.0, 0.0))
                if last.get(key) != (v, t):
                    lines.append((ymd(r["Date"]), iso, key, v, t))
                    last[key] = (v, t)

    # ROW weekly population-weighted average (weights from OxCGRT coverage only).
    others = [c for c in ox if c not in isos] if with_row else []
    weights = {c: pop_by_iso.get(c, 0.0) for c in others}
    by_date = defaultdict(lambda: defaultdict(float))
    tgt_date = defaultdict(lambda: defaultdict(float))
    wsum = defaultdict(float)
    for c in others:
        wc = weights[c]
        if wc <= 0:
            continue
        for r in ox[c]:
            d = r["Date"]
            wsum[d] += wc
            for key, col in NPI_COLUMNS.items():
                v, t = npi_level(r, col)
                by_date[d][key] += wc * (v or 0.0)
                tgt_date[d][key] += wc * t
    last = {}
    for d in sorted(by_date):
        if dt.date.fromisoformat(ymd(d)).weekday() != 0 and d != "20200101":
            continue  # weekly (Mondays)
        for key in NPI_COLUMNS:
            v = round(by_date[d][key] / wsum[d] * 4) / 4  # quarter-level steps
            t = round(tgt_date[d][key] / wsum[d] * 4) / 4
            if last.get(key) != (v, t):
                lines.append((ymd(d), ROW, key, v, t))
                last[key] = (v, t)
    lines.sort()
    out = [f"# {GEN}", "# Source: OxCGRT national compact v1 (CC BY 4.0). One event per level change.",
           "# targeted = share of the measure that is regional rather than nationwide (OxCGRT _Flag = 0).", ""]
    for d, iso, key, v, t in lines:
        extra = f" targeted{{{fmt(t, 2)}}}" if t > 0 else ""
        out.append(f"npi{{ date{{{d}}} nation{{{iso}}} indicator{{{key}}} level{{{fmt(v, 2)}}}{extra} }}")
    return "\n".join(out) + "\n", len(lines)


def fiscal_events(ox, nations, isos=SLICE):
    out = [f"# {GEN}",
           "# Source: OxCGRT E3 (announced fiscal measures, USD). Scaled by",
           f"# above_line_fraction={FISCAL_ABOVE_LINE_FRACTION}, capped at {FISCAL_CAP_PCT_GDP}% of 2019 GDP per nation.",
           "# Override per nation in assets/scenario/2020/nations_curated.csv (fiscal_pct_gdp_override).", ""]
    n = 0
    for iso in isos:
        gdp = nations[iso]["gdp_usd"]
        items = [(ymd(r["Date"]), num(r["E3_Fiscal measures"]) or 0.0) for r in ox.get(iso, [])]
        items = [(d, v) for d, v in items if v > 0]
        total_pct = sum(v for _, v in items) / gdp * 100 * FISCAL_ABOVE_LINE_FRACTION
        override = nations[iso].get("fiscal_pct_gdp_override")
        target_pct = float(override) if override not in (None, "") else min(total_pct, FISCAL_CAP_PCT_GDP)
        scale = target_pct / total_pct if total_pct > 0 else 0.0
        for d, v in items:
            pct = v / gdp * 100 * FISCAL_ABOVE_LINE_FRACTION * scale
            if pct < 0.01:
                continue
            out.append(f"fiscal_package{{ date{{{d}}} nation{{{iso}}} pct_gdp{{{fmt(pct, 3)}}} }}")
            n += 1
    return "\n".join(out) + "\n", n


# Seeding follows Flaxman et al. (2020, Nature 584:257): the epidemic is seeded
# 30 days before cumulative reported deaths first reach 10. Confirmed cases are
# a poor guide in early 2020 because almost all infections went undetected.
SEED_DEATHS = 10
SEED_LEAD_DAYS = 30
SEED_INFECTIONS = 300  # ~ (10 deaths / 0.8% IFR) / 4: growth over the lead time supplies the rest


def epidemic_seeds(ox, isos=SLICE):
    out = [f"# {GEN}",
           f"# Source: OxCGRT ConfirmedDeaths. Seed {SEED_INFECTIONS} infections {SEED_LEAD_DAYS} days before cumulative",
           f"# reported deaths reach {SEED_DEATHS} (Flaxman et al. 2020). China is seeded in curated.txt.", ""]
    for iso in isos:
        if iso == "CHN":
            continue
        for r in ox.get(iso, []):
            deaths = num(r["ConfirmedDeaths"]) or 0.0
            if deaths >= SEED_DEATHS:
                d = dt.date.fromisoformat(ymd(r["Date"])) - dt.timedelta(days=SEED_LEAD_DAYS)
                d = max(d, dt.date(2020, 1, 1))
                out.append(f"epidemic_seed{{ date{{{d.isoformat()}}} nation{{{iso}}} pathogen{{cov}} infections{{{SEED_INFECTIONS}}} }}")
                break
    return "\n".join(out) + "\n"


