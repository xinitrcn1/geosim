#!/usr/bin/env python3
"""Build the 2008 calibration slice (assets/scenario/2008, events/2008, backtest/2008_*).

Same nations as the 2020 slice (G20 + ESP + ROW). The initial state is the end of
2007; back-test targets are the 2008 outcomes (onset of the Global Financial Crisis)
and the 2009 outcomes (its trough). Generated here:
  assets/scenario/2008/nations.csv        macro state (WDI, latest year <= 2007)
  assets/scenario/2008/sectors.csv        7-sector split (as in the 2020 slice)
  assets/events/2008/policy_rates.txt     BIS policy rates: 2008-01-01 level + changes to 2009-12-31
  assets/backtest/2008_targets.csv        real 2008 outcomes (WDI)
  assets/backtest/2008_y2_targets.csv     real 2009 outcomes (WDI; scored by backtest --years 2)
  assets/backtest/2008_brent.csv          daily Brent 2008 (EIA)
Hand-written (never overwritten): assets/scenario/2008/*_curated.csv and
assets/events/2008/curated.txt (the crisis shocks and policy anchors, with sources).

Run fetch.py first (it downloads data/raw/wdi2008 and bis_cbpol_2008.csv).
Usage: python3 tools/pipeline/build_slice2008.py [--raw data/raw] [--assets assets]
"""

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_assets as ba  # noqa: E402
from countries import SLICE, ROW, ISO2  # noqa: E402

GEN = "generated by tools/pipeline/build_slice2008.py - edit the pipeline or the *_curated files"
STATE_YEAR = 2007
EURO_AREA_2008 = {"DEU", "FRA", "ITA", "ESP"}  # slice members of the euro area in 2008


def targets(wdi, year):
    rows = []
    for iso in SLICE:
        g = lambda f: wdi[f].get(iso, {}).get(year)
        rows.append([iso, g("real_gdp_growth_pct"), g("unemployment_pct"), g("cpi_inflation_pct"),
                     g("gov_net_lending_pct"), None])
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw")
    ap.add_argument("--assets", default="assets")
    args = ap.parse_args()
    raw, assets = pathlib.Path(args.raw), pathlib.Path(args.assets)
    scen = assets / "scenario" / "2008"
    events = assets / "events" / "2008"
    events.mkdir(parents=True, exist_ok=True)

    wdi = ba.load_wdi(raw, "wdi2008")
    curated = ba.read_curated(scen / "nations_curated.csv")
    nations = ba.build_nations(wdi, curated, year=STATE_YEAR)
    wgi = ba.load_wgi(raw, "wdi2008")
    coords = {}
    meta_path = raw / "wb_countries.json"
    if meta_path.exists():
        for c in json.loads(meta_path.read_text())[1]:
            if c.get("latitude"):
                coords[c["id"]] = (float(c["latitude"]), float(c["longitude"]))
    for iso in nations:
        nations[iso]["capital_lat"], nations[iso]["capital_lon"] = coords.get(iso, (20.0, 20.0))
    for field, col in (("voice", "voice_est"), ("effectiveness", "gov_effectiveness_est")):
        for iso in nations:
            nations[iso][col] = wgi[field].get(iso)
        rest = [v for k, v in wgi[field].items() if k not in nations]
        nations[ROW][col] = sum(rest) / len(rest) if rest else 0.0

    cols = ["iso3", "name", "population", "pop_0_14_pct", "pop_65up_pct", "labor_force",
            "unemployment_pct", "lfp_rate_pct", "gdp_usd", "gdp_ppp", "trend_growth_pct",
            "inflation_trend_pct", "hh_cons_pct", "gov_cons_pct", "investment_pct", "exports_pct",
            "imports_pct", "gov_revenue_pct", "gov_net_lending_pct", "gov_debt_pct", "gini",
            "hospital_beds_per_1000", "tertiary_attainment_pct", "urban_pct", "vulnerable_emp_pct",
            "voice_est", "gov_effectiveness_est", "birth_rate_per_1000", "death_rate_per_1000",
            "capital_lat", "capital_lon", "remittances_in_pct", "remittances_out_usd"]
    order = SLICE + [ROW]
    ba.write_csv(scen / "nations.csv", cols, [[nations[i].get(c) for c in cols] for i in order],
                 f"{GEN}. Source: World Bank WDI, latest year <= {STATE_YEAR}; WGI 2003-{STATE_YEAR} "
                 f"voice/effectiveness (ROW: unweighted mean of the rest). Empty = missing (loader uses defaults).")
    srows = []
    for iso in order:
        va, emp = ba.sector_split(wdi, iso, nations[iso], year=STATE_YEAR)
        for s in ba.SECTORS:
            srows.append([iso, s, va[s], emp[s]])
    ba.write_csv(scen / "sectors.csv", ["iso3", "sector", "va_share", "emp_share"], srows,
                 f"{GEN}. Source: WDI 3-sector VA/employment + resource rents ({STATE_YEAR}), split into 7 sectors.")

    text, n_rates = ba.policy_rate_events(raw, "bis_cbpol_2008.csv", iso2=ISO2, euro=EURO_AREA_2008,
                                          start="2008-01-01", end="2009-12-31")
    (events / "policy_rates.txt").write_text(text.replace(ba.GEN, GEN))

    header = ["iso3", "gdp_growth_pct", "unemployment_pct", "inflation_pct", "gov_net_lending_pct", "deaths_per_million"]
    ba.write_csv(assets / "backtest" / "2008_targets.csv", header, targets(wdi, 2008),
                 f"{GEN}. Real 2008 outcomes: WDI (growth, unemployment, CPI inflation, central-government net lending).")
    ba.write_csv(assets / "backtest" / "2008_y2_targets.csv", header, targets(wdi, 2009),
                 f"{GEN}. Real 2009 outcomes (the GFC trough): WDI.")
    ba.write_csv(assets / "backtest" / "2008_brent.csv", ["date", "usd_per_barrel"], ba.brent(raw, 2008),
                 f"{GEN}. Brent daily spot, EIA RBRTE.")
    print(f"nations={len(order)} rate_events={n_rates}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
