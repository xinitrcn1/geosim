#!/usr/bin/env python3
"""Build the full-world 2020 scenario (assets/scenario/world2020, events/world2020).

Nations: every World Bank economy with a 2019 population, plus hand-written
extras (nations_extra_curated.csv, e.g. Taiwan). Missing WDI values are imputed
with the median of the nation's World Bank income group.

Regions: geoBoundaries gbOpen ADM1 polygons (one region for nations without
ADM1 data). Regional estimates, all documented proxies to be replaced by
gridded data (WorldPop, DOSE) later:
  population share  = 0.98 x share of Natural Earth populated-place population
                      + 0.02 x share of land area (weights fitted to census shares of
                      27 reference regions in USA/IND/CHN/DEU/BRA: mean error x1.5)
  jurisdictions     = dependent territories (Hong Kong, Macau, Puerto Rico, ...) are
                      nations with a sovereignty link (jurisdictions_curated.csv); a
                      region duplicated in a sovereign's or claimant's ADM1 file belongs
                      to the jurisdiction / holder, and claims.csv records claims
                      (claims_curated.csv plus such duplicates). geoBoundaries gbOpen
                      2020 files have no such duplicates (China's excludes HKG, MAC, TWN).
  urban share       = place population / estimated population, rescaled to the
                      national urbanisation rate
  GDP share         = population share x (1 + URBAN_PREMIUM x (urban_r - urban_n))
  sector mix        = derived at load (scenario.cpp derive_region_sectors: the national mix
                      tilted by sectors.txt region_tilt, RAS-balanced)
  adjacency         = ADM1 polygons sharing boundary vertices (within a nation)

Usage: python3 tools/pipeline/build_world.py [--raw data/raw] [--assets assets]
"""

