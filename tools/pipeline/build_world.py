def wb_countries(raw):
    meta = json.loads((raw / "wb_countries.json").read_text())[1]
    out = {}
    for c in meta:
        if c["region"]["id"] == "NA":
            continue  # aggregates
        out[c["id"]] = {
            "name": c["name"], "iso2": c["iso2Code"], "income": c["incomeLevel"]["id"],
            "region": c["region"]["id"],
            "lat": float(c["latitude"]) if c["latitude"] else 0.0,
            "lon": float(c["longitude"]) if c["longitude"] else 0.0,
        }
    return out


def build_nations(wdi, countries, extra, fills=None):
    rows = {}
    for iso, meta in countries.items():
        g = lambda f: ba.latest(wdi, f, iso)
        if not g("population"):
            continue
        r = {"iso3": iso, "name": meta["name"], "income": meta["income"]}
        for f in NUMERIC:
            r[f] = g(f) if f in wdi else None
        # Published values from other datasets (world_extra.build): general-government debt and
        # balance replace WDI's central-government series; beds fill WDI's gaps.
        for f, vals in (fills or {}).items():
            if iso in vals and (f != "hospital_beds_per_1000" or not r.get(f)):
                r[f] = vals[iso]
        r["trend_growth_pct"] = ba.mean_years(wdi, "real_gdp_growth_pct", iso, range(2015, 2020))
        r["inflation_trend_pct"] = ba.mean_years(wdi, "cpi_inflation_pct", iso, range(2017, 2020))
        rows[iso] = r
    for iso, e in extra.items():
        r = {"iso3": iso, "name": e.get("name", iso), "income": e.get("income", "HIC")}
        for f in NUMERIC:
            v = e.get(f, "")
            r[f] = float(v) if v not in ("", None) else None
        rows[iso] = r
        countries.setdefault(iso, {"name": r["name"], "iso2": e.get("iso2", ""), "income": r["income"],
                                   "region": "", "lat": float(e.get("lat") or 0), "lon": float(e.get("lon") or 0)})

    # Levels: labour force and GDP are required; impute from population if missing.
    by_group = defaultdict(list)
    for r in rows.values():
        by_group[r["income"]].append(r)
    imputed = defaultdict(int)

    def median(field, group):
        ok = lambda v: v is not None and (field not in POSITIVE or v > 0)
        vals = [x[field] for x in by_group.get(group, []) if ok(x[field])]
        if not vals:
            vals = [x[field] for x in rows.values() if ok(x[field])]
        return statistics.median(vals) if vals else None

    gdp_pc = {g: median_ratio(by_group[g], "gdp_usd", "population") for g in by_group}
    per_gdp = {f: {g: median_ratio(by_group[g], f, "gdp_usd") or 0.0 for g in by_group} for f in IMPUTE_PER_GDP}
    per_pop = {f: {g: median_ratio(by_group[g], f, "population") or 0.0 for g in by_group} for f in IMPUTE_PER_POP}
    lf_rate = {g: median_ratio(by_group[g], "labor_force", "population") for g in by_group}
    for r in rows.values():
        if not r["gdp_usd"]:
            r["gdp_usd"] = r["population"] * gdp_pc[r["income"]]
            imputed["gdp_usd"] += 1
        if not r["gdp_ppp"]:
            r["gdp_ppp"] = r["gdp_usd"]
        if not r["labor_force"]:
            r["labor_force"] = r["population"] * lf_rate[r["income"]]
            imputed["labor_force"] += 1
        for f in IMPUTE_PER_GDP:
            if r[f] is None or r[f] < 0:
                r[f] = per_gdp[f][r["income"]] * r["gdp_usd"]
                imputed[f] += 1
        for f in IMPUTE_PER_POP:
            if r[f] is None or r[f] < 0:
                r[f] = per_pop[f][r["income"]] * r["population"]
                imputed[f] += 1
        for f in IMPUTE:
            # Expenditure and structure shares cannot be zero or negative; WDI reports 0 for
            # some discontinued series (e.g. Venezuela after 2014) - treat them as missing.
            if r[f] is None or (f in POSITIVE and r[f] <= 0):
                r[f] = median(f, r["income"])
                imputed[f] += 1
        # COVID death reporting prior (main() replaces it with excess-mortality data where
        # available); labour institutions come from assets/defs/income_priors.csv at load and
        # the seasons from the capital's latitude.
        r["death_reporting"] = INSTITUTIONS.get(r["income"], INSTITUTIONS["UMC"])[3]
    return rows, imputed


def median_ratio(rows, num, den):
    vals = [r[num] / r[den] for r in rows if r.get(num) and r.get(den)]
    return statistics.median(vals) if vals else 0.0


def ras(matrix, row_targets, col_targets, iters=300):
    m = [list(r) for r in matrix]
    for _ in range(iters):
        for j in range(len(col_targets)):
            s = sum(m[i][j] for i in range(len(m)))
            if s > 0:
                for i in range(len(m)):
                    m[i][j] *= col_targets[j] / s
        for i in range(len(m)):
            s = sum(m[i])
            if s > 0:
                m[i] = [v * row_targets[i] / s for v in m[i]]
    return m


def load_places(raw):
    feats = json.loads((raw / "ne_populated_places.geojson").read_text())["features"]
    out = defaultdict(list)
    for f in feats:
        p = f["properties"]
        iso = p.get("adm0_a3") or p.get("sov_a3")
        pop = p.get("pop_max") or 0
        lon, lat = f["geometry"]["coordinates"][:2]
        out[iso].append((lon, lat, float(pop)))
    return out


def load_boundaries(raw, nations):
    """iso -> list of (feature, polygons); plus total area per nation."""
    out, total = {}, {}
    for iso in nations:
        path = raw / "geoboundaries" / f"{iso}.geojson"
        feats = []
        if path.exists():
            try:
                feats = json.loads(path.read_text()).get("features", [])
            except json.JSONDecodeError:
                feats = []
        for code, name, iso_code in EXTRA_ADM1.get(iso, []):
            mu = map_units(raw).get(code)
            if mu is None:
                print(f"warning: no Natural Earth map unit {code} for {iso}")
                continue
            feats.append({"type": "Feature", "geometry": mu["geometry"],
                          "properties": {"shapeName": name, "shapeISO": iso_code, "pop_est": mu["properties"].get("POP_EST")}})
        items = []
        for f in feats:
            rp = geo.rings_of(f.get("geometry") or {"type": "None"})
            if rp:
                items.append((f, rp, geo.bbox(rp)))
        out[iso] = items
        total[iso] = sum(geo.area_and_centroid(rp)[0] for _, rp, _ in items)
    return out, total


# Jurisdictions. Dependent territories inside a sovereign's ADM1 file (Hong Kong and Macau
# in China's, ...) are their own nations with a sovereignty link
# (jurisdictions_curated.csv, read by the scenario loader); claimed territory duplicated in
# a claimant's file (Taiwan in China's) belongs to its holder and becomes a claim
# (claims.csv = claims_curated.csv + the duplicates found here). Regions are only
# reassigned between such pairs, so neighbours sharing a border (Noord-Brabant and the
# Baarle-Hertog enclaves) are never confused.


def read_pairs(path, a, b):
    """(a, b) pairs from a curated csv, e.g. (sovereign, jurisdiction)."""
    if not path.exists():
        return set()
    rows = csv.DictReader(line for line in path.open() if not line.startswith("#"))
    return {(r[a], r[b]) for r in rows}


# Subdivisions of a sovereign's ADM1 file that the scenario models as their own nation (a
# dependency or a claimed holder) but that have no ADM1 polygons of their own, so the
# polygon test below cannot find them: matched by ISO 3166-2 code or by name. They used to
# stay in the sovereign as duplicates (Macau held 0.3% of China's population).
TERRITORY_CODES = {"US-PR": "PRI", "US-AS": "ASM", "US-VI": "VIR", "US-GU": "GUM", "US-MP": "MNP",
                   "CN-HK": "HKG", "CN-MO": "MAC", "CN-TW": "TWN"}
TERRITORY_NAMES = {"hong kong": "HKG", "macau": "MAC", "macao": "MAC", "taiwan": "TWN", "puerto rico": "PRI",
                   "guam": "GUM", "american samoa": "ASM", "virgin islands": "VIR", "northern mariana": "MNP"}


def territory_of(iso, props, allowed):
    """The dependency / claimed holder of `iso` that ADM1 feature `props` duplicates, if any."""
    code = (props.get("shapeISO") or "").upper()
    other = TERRITORY_CODES.get(code)
    if other is None:
        name = (props.get("shapeName") or "").lower()
        other = next((v for k, v in TERRITORY_NAMES.items() if k in name), None)
    return other if other in allowed.get(iso, ()) else None


def owned_by_smaller(iso, rp, box, bounds, total, allowed, threshold=0.6):
    """A region of `iso` belongs to a smaller nation `other` (one of `allowed[iso]`: its
    dependencies and the territories it claims) if most of its boundary vertices lie inside it."""
    pts = [p for poly in rp for ring in poly for p in ring[::max(1, len(ring) // 40)]]
    for other, items in bounds.items():
        if other == iso or other not in allowed.get(iso, ()) or not items or total[other] >= total[iso]:
            continue
        for _, orp, b in items:
            if b[2] < box[0] or b[0] > box[2] or b[3] < box[1] or b[1] > box[3]:
                continue
            inside = sum(1 for x, y in pts if b[0] <= x <= b[2] and b[1] <= y <= b[3] and geo.point_in_polygons(x, y, orp))
            if pts and inside / len(pts) >= threshold:
                return other
    return None


def build_regions(raw, nations, countries, places, allowed):
    """-> regions list, adjacency list, dropped overlaps (iso, name, owner)."""
    regions = []
    adjacency = []
    dropped = []
    bounds, total = load_boundaries(raw, nations)
    for iso in sorted(nations):
        n = nations[iso]
        polys, info = [], []
        for k, (f, rp, box) in enumerate(bounds[iso]):
            area, (lon, lat) = geo.area_and_centroid(rp)
            props = f.get("properties", {})
            owner = territory_of(iso, props, allowed) or owned_by_smaller(iso, rp, box, bounds, total, allowed)
            if owner:
                dropped.append((iso, props.get("shapeName"), owner))
                continue
            polys.append(rp)
            info.append({"name": props.get("shapeName") or f"{iso}-{k}", "code": props.get("shapeISO") or "",
                         "area": area, "lon": lon, "lat": lat, "bbox": geo.bbox(rp), "pop_est": props.get("pop_est")})
        if not info:  # no ADM1 boundaries (e.g. Hong Kong, Macau): one region of the nation's land area
            info = [{"name": n["name"], "code": iso, "area": n.get("land_area_km2") or 1000.0,
                     "lon": countries[iso]["lon"], "lat": countries[iso]["lat"], "bbox": None}]
            polys = [[]]

        # Populated places -> regions.
        city = [0.0] * len(info)
        for (x, y, pop) in places.get(iso, []):
            hit = None
            for i, r in enumerate(info):
                b = r["bbox"]
                if b and b[0] <= x <= b[2] and b[1] <= y <= b[3] and geo.point_in_polygons(x, y, polys[i]):
                    hit = i
                    break
            if hit is None:  # simplified boundaries miss coastal points: nearest centroid
                hit = min(range(len(info)), key=lambda i: (info[i]["lon"] - x) ** 2 + (info[i]["lat"] - y) ** 2)
            city[hit] += pop
        tot_city = sum(city)
        tot_area = sum(r["area"] for r in info) or 1.0
        pop_share = []
        for i, r in enumerate(info):
            s = (PLACE_WEIGHT * city[i] / tot_city if tot_city > 0 else 0.0) \
                + ((1 - PLACE_WEIGHT) if tot_city > 0 else 1.0) * r["area"] / tot_area
            pop_share.append(s)
        # Every region keeps a sliver of population (uninhabited ADM1 units still exist).
        pop_share = [max(s, 1e-6) for s in pop_share]
        ps = sum(pop_share) or 1.0
        pop_share = [s / ps for s in pop_share]
        # Regions with a published population estimate (EXTRA_ADM1) take it; the rest share
        # the remainder in their estimated proportions.
        known = {i: r["pop_est"] / n["population"] for i, r in enumerate(info) if r.get("pop_est") and n["population"]}
        if known and sum(known.values()) < 1.0:
            rest = sum(s for i, s in enumerate(pop_share) if i not in known) or 1.0
            left = 1.0 - sum(known.values())
            pop_share = [known[i] if i in known else s * left / rest for i, s in enumerate(pop_share)]

        urban_n = (n["urban_pct"] or 50.0) / 100.0
        raw_urban = [min(1.0, city[i] / max(1.0, pop_share[i] * n["population"])) for i in range(len(info))]
        mean_raw = sum(u * s for u, s in zip(raw_urban, pop_share)) or 1.0
        urban = [min(1.0, u * urban_n / mean_raw) for u in raw_urban]
        gdp_w = [pop_share[i] * max(MIN_GDP_FACTOR, 1 + URBAN_PREMIUM * (urban[i] - urban_n)) for i in range(len(info))]
        gs = sum(gdp_w) or 1.0
        gdp_share = [g / gs for g in gdp_w]

        base = len(regions)
        for i, r in enumerate(info):
            regions.append({"id": f"{iso}-{i:03d}", "iso3": iso, "name": r["name"], "code": r["code"],
                            "lat": r["lat"], "lon": r["lon"], "area_km2": r["area"], "pop_share": pop_share[i],
                            "gdp_share": gdp_share[i], "urban_share": urban[i], "polys": polys[i]})
        if len(info) > 1:
            pairs = geo.shared_vertex_adjacency(polys)
            linked = set()
            for (i, j), wgt in pairs.items():
                adjacency.append((regions[base + i]["id"], regions[base + j]["id"], wgt))
                linked.update((i, j))
            for i in range(len(info)):  # islands: link to the nearest region
                if i not in linked:
                    j = min((k for k in range(len(info)) if k != i),
                            key=lambda k: geo.haversine_km((info[i]["lon"], info[i]["lat"]), (info[k]["lon"], info[k]["lat"])))
                    a, b = min(i, j), max(i, j)
                    adjacency.append((regions[base + a]["id"], regions[base + b]["id"], 1))
    return regions, adjacency, dropped


TWH_PER_MBD = 620.5  # 1 mb/d of oil for a year ~ 365e6 bbl x 1.70 MWh/bbl


def energy_shares(raw, nations, wdi):
    """Oil, gas and coal production and consumption per nation, 2019 (Energy Institute via
    Our World in Data). Nations the dataset lists only inside regional aggregates share the
    remainder of the world total: production by the WDI resource rents (rents % GDP x GDP),
    consumption by PPP GDP. -> {fuel: {iso: (production_share, consumption_share)}},
    world oil (production_mbd, consumption_mbd)."""
    path = raw / "owid_energy.csv"
    if not path.exists():
        return {}, None
    rows, world = {}, None
    with path.open(newline="") as f:
        for r in csv.DictReader(f):
            if r["year"] != "2019":
                continue
            if r["country"] == "World":
                world = r
            elif r["iso_code"] in nations:
                rows[r["iso_code"]] = r
    num = lambda v: float(v) if v not in ("", None) else None
    rent_field = {"oil": "oil_rents_pct", "gas": "gas_rents_pct", "coal": "coal_rents_pct"}
    out = {}
    for fuel in ("oil", "gas", "coal"):
        wp, wc = num(world[f"{fuel}_production"]) or 0.0, num(world[f"{fuel}_consumption"]) or 0.0
        prod = {i: num(r[f"{fuel}_production"]) for i, r in rows.items()}
        cons = {i: num(r[f"{fuel}_consumption"]) for i, r in rows.items()}
        listed_p = sum(v for v in prod.values() if v)
        listed_c = sum(v for v in cons.values() if v)
        rest_p, rest_c = max(0.0, wp - listed_p), max(0.0, wc - listed_c)
        rents = {i: (ba.latest(wdi, rent_field[fuel], i) or 0.0) / 100.0 * (nations[i]["gdp_usd"] or 0.0)
                 for i in nations if not prod.get(i)}
        ppp = {i: nations[i]["gdp_ppp"] or 0.0 for i in nations if not cons.get(i)}
        rt, pt = sum(rents.values()) or 1.0, sum(ppp.values()) or 1.0
        shares = {}
        for i in nations:
            p_ = prod.get(i) or rest_p * rents.get(i, 0.0) / rt
            c_ = cons.get(i) or rest_c * ppp.get(i, 0.0) / pt
            shares[i] = (p_ / wp if wp else 0.0, c_ / wc if wc else 0.0)
        out[fuel] = shares
    return out, (num(world["oil_production"]) / TWH_PER_MBD, num(world["oil_consumption"]) / TWH_PER_MBD)


def excess_deaths_2020(raw):
    """Estimated excess deaths in 2020 per million (The Economist model, central): weekly
    rows of daily averages, so the year's total is 7x their sum."""
    path = raw / "economist_excess.csv"
    if not path.exists():
        return {}
    ex, pop = defaultdict(float), {}
    with path.open(newline="") as f:
        for r in csv.DictReader(f):
            if r["date"] > "2020-12-31":
                continue
            try:
                ex[r["iso3c"]] += 7.0 * float(r["estimated_daily_excess_deaths"] or 0)
                pop[r["iso3c"]] = float(r["population"])
            except ValueError:
                continue
    return {i: max(0.0, ex[i]) / pop[i] * 1e6 for i in ex if pop.get(i)}


def death_reporting_2020(raw):
    """Reported COVID deaths / estimated excess deaths in 2020 per nation (The Economist's
    excess-deaths model, central estimate; both series on the same dates, so the ratio does
    not depend on the sampling). Where excess deaths were not positive (Japan, New Zealand,
    ...) or below reported deaths, reporting is taken as complete."""
    path = raw / "economist_excess.csv"
    if not path.exists():
        return {}
    ex, cov = defaultdict(float), defaultdict(float)
    with path.open(newline="") as f:
        for r in csv.DictReader(f):
            if r["date"] > "2020-12-31":
                continue
            try:
                ex[r["iso3c"]] += float(r["estimated_daily_excess_deaths"] or 0)
                cov[r["iso3c"]] += float(r["daily_covid_deaths"] or 0)
            except ValueError:
                continue
    out = {}
    for iso in ex:
        if ex[iso] <= 0 or cov[iso] >= ex[iso]:
            out[iso] = 1.0
        elif cov[iso] > 0:
            out[iso] = max(0.02, cov[iso] / ex[iso])
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw")
    ap.add_argument("--assets", default="assets")
    args = ap.parse_args()
    raw, assets = pathlib.Path(args.raw), pathlib.Path(args.assets)
    scen = assets / "scenario" / SCENARIO
    events = assets / "events" / SCENARIO
    events.mkdir(parents=True, exist_ok=True)

    wdi = ba.load_wdi(raw, "wdi_all")
    countries = wb_countries(raw)
    places = load_places(raw)
    places_cached = places
    # Economies without World Bank capital coordinates (Channel Islands, Curacao, Gibraltar,
    # St. Martin, Sint Maarten) take their largest Natural Earth populated place; the
    # default (0, 0) would put them in the Gulf of Guinea (distances, freight, seasons).
    for iso, c in countries.items():
        if c.get("lat") or c.get("lon"):
            continue
        cands = [p for code in PLACE_ALIASES.get(iso, [iso]) for p in places.get(code, [])]
        if cands:
            lon, lat, _ = max(cands, key=lambda t: t[2])
        elif iso in CAPITALS:
            lat, lon = CAPITALS[iso]
        else:
            print(f"warning: no coordinates for {iso}")
            continue
        c["lon"], c["lat"] = lon, lat
        print(f"coordinates for {iso}: {lat:.2f}, {lon:.2f}")
    extra = ba.read_curated(scen / "nations_extra_curated.csv")
    # Society, finance, extension and logistics tables, and fills of nations.csv gaps.
    pop_only = {iso: {"population": ba.latest(wdi, "population", iso)} for iso in countries if ba.latest(wdi, "population", iso)}
    extra_tables, extra_fills, extra_report = world_extra.build(raw, pop_only, countries)
    nations, imputed = build_nations(wdi, countries, extra, extra_fills)
    order = sorted(nations)
    # COVID death reporting from excess-mortality estimates where available (else the
    # income-group prior).
    reporting = death_reporting_2020(raw)
    for iso in order:
        if iso in reporting:
            nations[iso]["death_reporting"] = reporting[iso]
    print(f"death reporting from excess mortality: {sum(1 for i in order if i in reporting)} nations")

    # Energy: oil production / consumption per nation (mb/d at the dataset's world total),
    # gas and coal shares (commodities.csv).
    energy, oil_world = energy_shares(raw, nations, wdi)
    if energy:
        for iso in nations:
            p_, c_ = energy["oil"][iso]
            nations[iso]["oil_production_mbd"] = p_ * oil_world[0]
            nations[iso]["oil_consumption_mbd"] = c_ * oil_world[1]
    # Institutions: WGI voice and accountability / government effectiveness (latest
    # estimate); nations without WGI take their income group's median. Voice sets the
    # electoral and liberal indices (scenario.cpp), so without it every nation looked like a
    # middling democracy.
    wgi = ba.load_wgi(raw)
    for field, col in (("voice", "voice_est"), ("effectiveness", "gov_effectiveness_est")):
        by_group = defaultdict(list)
        for iso in order:
            v = wgi[field].get(iso)
            if v is not None:
                by_group[nations[iso]["income"]].append(v)
        missing = 0
        for iso in order:
            v = wgi[field].get(iso)
            if v is None:
                grp = by_group[nations[iso]["income"]]
                v = statistics.median(grp) if grp else 0.0
                missing += 1
            nations[iso][col] = v
        print(f"WGI {field}: {len(order) - missing} nations from data, {missing} imputed")
    # Capital coordinates (World Bank metadata, Natural Earth fallback): distances for trade
    # gravity, threat and logistics. Without them every nation sat at (0, 0) and gravity
    # weighted partners by GDP alone (docs/13).
    for iso in order:
        nations[iso]["capital_lat"] = countries.get(iso, {}).get("lat", 0.0)
        nations[iso]["capital_lon"] = countries.get(iso, {}).get("lon", 0.0)
    # Military expenditure (SIPRI via WDI, % of GDP, latest <= 2019); income-group median otherwise.
    by_group = defaultdict(list)
    for iso in order:
        v = ba.latest(wdi, "defense_pct", iso)
        if v is not None:
            by_group[nations[iso]["income"]].append(v)
    for iso in order:
        v = ba.latest(wdi, "defense_pct", iso)
        grp = by_group[nations[iso]["income"]]
        nations[iso]["defense_pct"] = v if v is not None else (statistics.median(grp) if grp else 1.5)
    # lfp_rate_pct only imputes the labour force here; epl / benefits / hemisphere are derived at load.
    cols = ["iso3", "name", "income"] + [c for c in NUMERIC if c != "lfp_rate_pct"] + [
        "death_reporting", "oil_production_mbd", "oil_consumption_mbd", "voice_est", "gov_effectiveness_est", "defense_pct",
        "capital_lat", "capital_lon"]
    ba.write_csv(scen / "nations.csv", cols, [[nations[i].get(c) for c in cols] for i in order],
                 f"{GEN}. Source: World Bank WDI (latest <= 2019); general-government debt and balance from the World Bank "
                 f"Fiscal Space Database (IMF WEO-based); hospital beds WDI, else WHO GHO; remaining gaps imputed by "
                 f"income-group median ({', '.join(f'{k}:{v}' for k, v in sorted(imputed.items()))}).")
    for name, (head, rows) in extra_tables.items():
        rows = [r for r in rows if r[0] in nations]
        ba.write_csv(scen / name, head, rows, f"{GEN}. Sources and derivations: tools/pipeline/world_extra.py "
                                               f"(nations without data in a column keep the loader's default).")
    print("world extras:", extra_report)

    # Sector split with income-group medians as fallback for 3-sector data.
    group_vals = defaultdict(lambda: defaultdict(list))
    for iso in order:
        for f in ("va_agr_pct", "va_ind_pct", "va_man_pct", "va_srv_pct", "emp_agr_pct", "emp_ind_pct", "emp_srv_pct"):
            v = ba.latest(wdi, f, iso)
            if v is not None:
                group_vals[nations[iso]["income"]][f].append(v)
    nation_sectors = {}
    srows = []
    for iso in order:
        grp = nations[iso]["income"]
        fb = lambda f, grp=grp: statistics.median(group_vals[grp][f]) if group_vals[grp][f] else None
        va, emp = ba.sector_split(wdi, iso, nations[iso], fallback=fb)
        nation_sectors[iso] = (va, emp)
        for s in ba.SECTORS:
            srows.append([iso, s, va[s], emp[s]])
    if energy:
        crows = [[iso, fuel, f"{energy[fuel][iso][0]:.6g}", f"{energy[fuel][iso][1]:.6g}"]
                 for fuel in ("gas", "coal") for iso in order if any(energy[fuel][iso])]
        ba.write_csv(scen / "commodities.csv", ["iso3", "commodity", "production_share", "consumption_share"], crows,
                     f"{GEN}. Gas and coal production / consumption shares of the world, 2019: Energy Institute "
                     f"Statistical Review via Our World in Data (CC BY 4.0); unlisted nations share the remainder "
                     f"by WDI rents (production) and PPP GDP (consumption).")
    ba.write_csv(scen / "sectors.csv", ["iso3", "sector", "va_share", "emp_share"], srows,
                 f"{GEN}. 7-sector split as in the 2020 slice; income-group medians where WDI has gaps.")

    places = places_cached
    dependencies = read_pairs(scen / "jurisdictions_curated.csv", "sovereign", "iso3")
    claimed = read_pairs(scen / "claims_curated.csv", "claimant", "holder")
    allowed = defaultdict(set)
    for a, b in dependencies | claimed:
        allowed[a].add(b)
    regions, adjacency, dropped = build_regions(raw, nations, countries, places, allowed)
    print("duplicated regions assigned to their jurisdiction:", ", ".join(f"{a}:{n}->{o}" for a, n, o in dropped))
    # Claims: curated, plus territory a claimant's boundary file duplicates (not a dependency).
    claims = {(a, b): s for a, b, s in ((r["claimant"], r["holder"], r["strength"])
              for r in csv.DictReader(line for line in (scen / "claims_curated.csv").open() if not line.startswith("#")))} \
        if (scen / "claims_curated.csv").exists() else {}
    derived = {(a, o): "1.0" for a, _, o in dropped if (a, o) not in dependencies and (a, o) not in claims}
    # Only the claims found here: the loader reads claims_curated.csv as well.
    if derived:
        ba.write_csv(scen / "claims.csv", ["claimant", "holder", "strength"],
                     [[a, b, s] for (a, b), s in sorted(derived.items()) if a in nations and b in nations],
                     f"{GEN}. Territory duplicated in a claimant's ADM1 file (claims_curated.csv is read as well).")
    elif (scen / "claims.csv").exists():
        (scen / "claims.csv").unlink()
    # States are the ADM1 units; the simulation's regions are clusters of their counties (ADM2)
    # sized by population (adm2.py). Territories without ADM1 data take their Natural Earth shape.
    ne_path = raw / "map" / "ne_10m_admin_0_countries.geojson"
    if ne_path.exists():
        ne_by = defaultdict(list)
        for f in json.loads(ne_path.read_text(encoding="utf-8"))["features"]:
            p = f["properties"]
            for key in ("ADM0_A3", "ISO_A3", "SOV_A3"):
                if p.get(key) and p[key] != "-99":
                    ne_by[p[key]].append(f)
                    break
        for r in regions:
            if not r["polys"] or r["polys"] == []:
                r["polys"] = [poly for code in {"CHI": ["JEY", "GGY"], "XKX": ["KOS"]}.get(r["iso3"], [r["iso3"]])
                              for f in ne_by.get(code, []) for poly in geo.rings_of(f["geometry"])]
    urban_n = {iso: (nations[iso]["urban_pct"] or 50.0) / 100.0 for iso in nations}
    # Pops per region: 4 per identity group (groups_curated.csv here or in the base scenario;
    # one group elsewhere), for the clusters' pop budget.
    groups = defaultdict(int)
    for gpath in (scen / "groups_curated.csv", assets / "scenario" / "2020" / "groups_curated.csv"):
        if gpath.exists():
            seen = defaultdict(int)
            for r in csv.DictReader(line for line in gpath.open() if not line.startswith("#")):
                seen[r["iso3"]] += 1
            for iso, k in seen.items():
                groups[iso] = groups[iso] or k
            break
    ppr = {iso: 4 * max(1, groups.get(iso, 1)) for iso in nations}
    clusters, adm2_rows, adjacency, states, _units = adm2.build(raw, regions, allowed, urban_n, ppr)
    ba.write_csv(scen / "states.csv", ["state", "iso3", "name", "code", "lat", "lon"],
                 [[s["state"], s["iso3"], s["name"], s["code"], s["lat"], s["lon"]] for s in states],
                 f"{GEN}. The states: geoBoundaries ADM1 (+ Natural Earth map units for France's overseas regions).")
    # Regional GDP and sector mix are derived at load from pop_share and urban_share
    # (scenario.cpp derive_region_sectors), so neither gdp_share nor region_sectors.csv ships.
    ba.write_csv(scen / "regions.csv", ["region", "iso3", "state", "name", "code", "lat", "lon", "area_km2", "pop_share",
                                        "urban_share"],
                 # Shares at full precision (four decimals would round small islands to zero).
                 [[r["id"], r["iso3"], r["state"], r["name"], r["code"], round(r["lat"], 4), round(r["lon"], 4), round(r["area_km2"], 1),
                   f"{r['pop_share']:.8g}", round(r["urban_share"], 4)] for r in clusters],
                 f"{GEN}. Clusters of counties (geoBoundaries ADM2) inside each state, sized by population "
                 f"(GHS-POP 2020; adm2.py): the simulation's regions.")
    ba.write_csv(scen / "adm2.csv", ["adm2", "name", "region", "pop"],
                 [[a["key"], a["name"], a["region"], a["pop"]] for a in adm2_rows],
                 f"{GEN}. Counties (geoBoundaries ADM2; a state without ADM2 data is one unit) and their cluster; "
                 f"population GHS-POP 2020. Drawn by the map (polygons in world.gsmap), simulated as clusters.")
    regions = clusters
    if (scen / "region_sectors.csv").exists():
        (scen / "region_sectors.csv").unlink()
    ba.write_csv(scen / "adjacency.csv", ["region_a", "region_b", "weight"], adjacency,
                 f"{GEN}. Within-nation neighbouring clusters (shared county borders on the 2.5' grid; islands to the nearest).")

    # Events.
    ox = ba.load_oxcgrt(raw)
    pop_all = {i: nations[i]["population"] for i in order}
    with_ox = [i for i in order if i in ox]
    text, n_npi = ba.npi_events(ox, pop_all, isos=with_ox, with_row=False)
    (events / "npi.txt").write_text(text)
    iso2 = {i: countries[i]["iso2"] for i in order if countries.get(i, {}).get("iso2")}
    text, n_rates = ba.policy_rate_events(raw, "bis_cbpol_all.csv", iso2=iso2, euro=EURO_AREA_2020)
    (events / "policy_rates.txt").write_text(text)
    text, n_fiscal = ba.fiscal_events(ox, nations, isos=with_ox)
    (events / "fiscal.txt").write_text(text)
    (events / "epidemic_seeds.txt").write_text(ba.epidemic_seeds(ox, isos=with_ox))

    excess = excess_deaths_2020(raw)
    trows = ba.targets(wdi, ox, nations, isos=[i for i in order if i in wdi["population"]])
    for r in trows:
        r.append(excess.get(r[0]))
    ba.write_csv(assets / "backtest" / f"{SCENARIO}_targets.csv",
                 ["iso3", "gdp_growth_pct", "unemployment_pct", "inflation_pct", "gov_net_lending_pct",
                  "deaths_per_million", "excess_deaths_per_million"],
                 trows,
                 f"{GEN}. Real 2020 outcomes: WDI, OxCGRT reported deaths to 2020-12-31, estimated excess "
                 f"deaths 2020 (The Economist model; scored against the model's true COVID deaths).")
    print(f"nations={len(order)} regions={len(regions)} adjacency={len(adjacency)} npi_events={n_npi} "
          f"rate_events={n_rates} fiscal_events={n_fiscal} imputed={dict(imputed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
